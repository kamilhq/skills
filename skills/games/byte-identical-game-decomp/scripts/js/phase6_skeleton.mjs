#!/usr/bin/env node
// JavaScript port of phase6_skeleton.py (same CLI, output files and stdout). Node built-ins only.
import { mkdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { dump, dumps, load } from './lib/pyjson.mjs'
import { ArgParser, cmp, cpSlice, hex, pyInt, pyStr, runMain } from './lib/pytools.mjs'

export const OWN = new Set(['method', 'ctor', 'dtor', 'free', 'stub'])

const truthy = (v) => !(v === null || v === undefined || v === false || v === 0 || v === '' ||
  (Array.isArray(v) && !v.length) || (v instanceof Map && !v.size) ||
  (typeof v === 'object' && typeof v.valueOf() === 'number' && v.valueOf() === 0))
const get = (f, k) => (f.has(k) ? f.get(k) : null)

export function main(argv) {
  const ap = new ArgParser('phase6_skeleton.py', [
    { name: 'names_final' }, { name: 'out' },
    { name: '--module', required: true }, { name: '--decompiled', default: 'decompiled_named_exe' },
    { name: '--gap', default: '0x400' },
  ])
  const a = ap.parse(argv)
  const gap = pyInt(a.gap, 0)
  const fs = load(a.names_final).map((f, i) => [pyInt(f.get('addr'), 16), i, f])
    .sort((x, y) => x[0] - y[0] || x[1] - y[1]).map((x) => x[2])
  const own = fs.filter((f) => OWN.has(get(f, 'kind')) && truthy(get(f, 'name')))
  const units = []
  let cur = null
  for (const f of own) {
    const ad = pyInt(f.get('addr'), 16)
    const sub = truthy(get(f, 'subsystem')) ? get(f, 'subsystem') : 'misc'
    if (cur && pyEq(sub, cur.subsystem) && ad - cur.last <= gap) {
      cur.functions.push(f)
      cur.last = ad
    } else {
      cur = { subsystem: sub, start: ad, last: ad, functions: [f] }
      units.push(cur)
    }
  }
  mkdirSync(a.out, { recursive: true })
  const index = []
  units.forEach((u, i) => {
    const cls = [...new Set(u.functions.filter((f) => f.get('name').includes('::')).map((f) => f.get('name').split('::')[0]))].sort(cmp)
    const stem = `${String(i).padStart(3, '0')}_${u.start.toString(16)}_${pyStr(u.subsystem)}`.replace(/[^A-Za-z0-9_]/gu, '_')
    const lines = [`// Translation-unit guess ${i}: ${pyStr(u.subsystem)}, ${u.functions.length} functions, ` +
                   `0x${u.start.toString(16)}..0x${u.last.toString(16)}` + (cls.length ? `; classes: ${cls.join(', ')}` : ''),
                   '// Generated by phase6_skeleton.py from phase-5 names. Write each function, then change STUB to',
                   '// FUNCTION and run objcmp.py report. Unit boundaries are guesses from address contiguity.', '']
    for (const f of u.functions) {
      const ev = get(f, 'evidence')
      lines.push(`// STUB: ${a.module} ${pyStr(f.get('addr'))}`,
                 `// ${pyStr(f.get('name'))}  (${pyStr(get(f, 'kind'))}, ${pyStr(get(f, 'subsystem'))}, ${pyStr(get(f, 'confidence'))})` +
                 (truthy(ev) ? ` - ${cpSlice(ev, 0, 150)}` : ''),
                 `// pseudocode: ${a.decompiled}/functions/${pyStr(f.get('addr'))}.c`, '')
    }
    writeFileSync(join(a.out, stem + '.cpp'), lines.join('\n'))
    index.push({ unit: stem, subsystem: u.subsystem, start: hex(u.start), end: hex(u.last),
                 functions: u.functions.map((f) => f.get('addr')) })
  })
  dump(index, join(a.out, 'units.json'), { indent: 1 })
  const skipped = fs.length - own.length
  process.stdout.write(dumps({ functions: fs.length, own_functions: own.length, units: units.length,
                               library_or_crt_or_unnamed: skipped }, { indent: 1 }) + '\n')
  return 0
}

// Python == for the JSON values a subsystem can hold
function pyEq(x, y) {
  if (x === y) return true
  const nx = typeof x === 'object' && x !== null && typeof x.valueOf() === 'number' ? x.valueOf() : x
  const ny = typeof y === 'object' && y !== null && typeof y.valueOf() === 'number' ? y.valueOf() : y
  if (typeof nx === 'number' && typeof ny === 'number') return nx === ny
  return dumps(x) === dumps(y) && typeof x === typeof y
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  runMain(() => main(process.argv.slice(2)))
}
