#!/usr/bin/env python3
"""Phase 6 prep: turn the phase-5 names into an annotated source skeleton for objcmp.py.

  phase6_skeleton.py <names_final.json> <out_src_dir> --module NAME [--decompiled <dir>] [--gap 0x400]

Writes one source file per translation-unit guess: address-contiguous runs of the program's own
functions (kinds method/ctor/dtor/free/stub) of the same subsystem, split where the gap to the next
own function exceeds --gap or the subsystem changes. Library and CRT functions (kind crt/lib/thunk) are
not listed: they are linked from the real libraries in the hybrid build. Each function becomes

    // STUB: NAME 0x401000 <decorated symbol unknown until compiled>
    // binaryBlob::unPackBinary  (method, file, high) - evidence ...
    // TODO: write C++; pseudocode: <decompiled>/functions/0x401000.c

STUB annotations never fail `objcmp.py report`; change STUB to FUNCTION once the function is written.
Also writes <out_src_dir>/units.json (unit -> functions, address range) and prints counts.
The output is derived from the game (names): keep it out of git (e.g. /src_matched/).
"""
import argparse, json, os, re

OWN = {'method', 'ctor', 'dtor', 'free', 'stub'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('names_final')
    ap.add_argument('out')
    ap.add_argument('--module', required=True)
    ap.add_argument('--decompiled', default='decompiled_named_exe')
    ap.add_argument('--gap', default='0x400')
    a = ap.parse_args()
    gap = int(a.gap, 0)
    fs = sorted(json.load(open(a.names_final)), key=lambda f: int(f['addr'], 16))
    own = [f for f in fs if f.get('kind') in OWN and f.get('name')]
    units, cur = [], None
    for f in own:
        ad = int(f['addr'], 16)
        sub = f.get('subsystem') or 'misc'
        if cur and sub == cur['subsystem'] and ad - cur['last'] <= gap:
            cur['functions'].append(f)
            cur['last'] = ad
        else:
            cur = dict(subsystem=sub, start=ad, last=ad, functions=[f])
            units.append(cur)
    os.makedirs(a.out, exist_ok=True)
    index = []
    for i, u in enumerate(units):
        cls = sorted({f['name'].split('::')[0] for f in u['functions'] if '::' in f['name']})
        stem = re.sub(r'[^A-Za-z0-9_]', '_', f"{i:03d}_{u['start']:x}_{u['subsystem']}")
        lines = [f'// Translation-unit guess {i}: {u["subsystem"]}, {len(u["functions"])} functions, '
                 f'0x{u["start"]:x}..0x{u["last"]:x}' + (f'; classes: {", ".join(cls)}' if cls else ''),
                 '// Generated by phase6_skeleton.py from phase-5 names. Write each function, then change STUB to',
                 '// FUNCTION and run objcmp.py report. Unit boundaries are guesses from address contiguity.', '']
        for f in u['functions']:
            lines += [f"// STUB: {a.module} {f['addr']}",
                      f"// {f['name']}  ({f.get('kind')}, {f.get('subsystem')}, {f.get('confidence')})"
                      + (f" - {f['evidence'][:150]}" if f.get('evidence') else ''),
                      f"// pseudocode: {a.decompiled}/functions/{f['addr']}.c", '']
        open(os.path.join(a.out, stem + '.cpp'), 'w').write('\n'.join(lines))
        index.append(dict(unit=stem, subsystem=u['subsystem'], start=hex(u['start']), end=hex(u['last']),
                          functions=[f['addr'] for f in u['functions']]))
    json.dump(index, open(os.path.join(a.out, 'units.json'), 'w'), indent=1)
    skipped = len(fs) - len(own)
    print(json.dumps(dict(functions=len(fs), own_functions=len(own), units=len(units),
                          library_or_crt_or_unnamed=skipped), indent=1))


if __name__ == '__main__':
    main()
